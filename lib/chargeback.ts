// Chargeback / dispute (Owner 2026-10-31): pure helpers shared by the webhook, email, and ops strip.
import { PDFDocument, StandardFonts, rgb } from "pdf-lib";

export const OPEN_DISPUTE_STATUSES = ["warning_needs_response", "warning_under_review", "needs_response", "under_review"] as const;

/** Red Chargeback pill shows only while a dispute is open/active. Won, lost, closed, or none: hidden. */
export function chargebackOpen(status: string | null | undefined): boolean {
  return !!status && (OPEN_DISPUTE_STATUSES as readonly string[]).includes(status);
}

export function chargebackEmail(o: { job: string; customer: string; amount: string; reason: string; status: string; openedAt: string; disputeId: string; url: string; stripeUrl?: string }) {
  const subject = `Chargeback evidence – Job #${o.job} – ${o.customer}`;
  const stripeLink = o.stripeUrl || `https://dashboard.stripe.com/disputes/${o.disputeId}`;
  const text = [
    "ATTN Ops — chargeback / dispute opened.",
    "A customer disputed a card payment with their bank.",
    "",
    "The attached PDF contains the signed contract, signed CC authorization, and carrier confirmation (if any). Each document has its own CRM-recorded date, time, signer, and IP address stamp at the top of that section.",
    "Download the PDF and upload it directly in Stripe under Customer signature.",
    "",
    `Amount disputed: ${o.amount}`,
    `Job: ${o.job}`,
    `Customer: ${o.customer}`,
    `Reason: ${o.reason || "—"}`,
    `Status: ${o.status}`,
    `Opened: ${o.openedAt}`,
    `Stripe dispute ID: ${o.disputeId}`,
    "",
    `Open this dispute in Stripe: ${stripeLink}`,
    "Instructions: Click Counter dispute → upload the attached PDF under Customer signature → fill any text fields → submit before the deadline.",
    "",
    `Open in CRM: ${o.url}`,
  ].join("\n");
  return { subject, text, stripeLink };
}

export type EvidenceStamp = {
  label: string;
  signedAt: string | null;
  signerName?: string | null;
  signerEmail?: string | null;
  ip?: string | null;
  html?: string | null;
};

/** Build one self-contained PDF evidence packet. Each document has its own stamp at the top of its section. */
export async function buildEvidencePdf(input: {
  job: string;
  customer: string;
  amount: string;
  reason: string;
  disputeId: string;
  openedAt: string;
  contract?: EvidenceStamp | null;
  ccAuth?: EvidenceStamp | null;
  carrierClick?: EvidenceStamp | null;
}): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  let page = pdf.addPage([612, 792]);
  let y = 750;
  const margin = 50;
  const lineHeight = 13;

  const draw = (text: string, size = 10, isBold = false) => {
    if (y < 50) {
      page = pdf.addPage([612, 792]);
      y = 750;
    }
    page.drawText(text.slice(0, 95), { x: margin, y, size, font: isBold ? bold : font, color: rgb(0, 0, 0) });
    y -= lineHeight;
  };

  // Cover header
  draw("Fastbreak CRM — Dispute Evidence Packet", 14, true);
  y -= 4;
  draw(`Job: ${input.job}`);
  draw(`Customer: ${input.customer}`);
  draw(`Amount disputed: ${input.amount}`);
  draw(`Reason: ${input.reason || "—"}`);
  draw(`Dispute ID: ${input.disputeId}`);
  draw(`Opened: ${input.openedAt}`);
  y -= 6;
  draw("Each section below is a separate document with its own CRM stamp at the top.", 9);
  y -= 14;

  const section = (title: string, stamp: EvidenceStamp | null | undefined) => {
    // Force a little space; new page if low
    if (y < 200) {
      page = pdf.addPage([612, 792]);
      y = 750;
    }
    draw(title, 12, true);
    y -= 2;
    draw("———————————————————————————————————————————", 9);
    if (!stamp) {
      draw("Not recorded.");
      y -= 10;
      return;
    }
    // Stamp block for THIS document only
    draw("CRM STAMP (recorded at time of action)", 10, true);
    if (stamp.signedAt) draw(`Date/Time: ${stamp.signedAt}`);
    if (stamp.signerName) draw(`Signer: ${stamp.signerName}`);
    if (stamp.signerEmail) draw(`Email: ${stamp.signerEmail}`);
    if (stamp.ip) draw(`IP Address: ${stamp.ip}`);
    draw("———————————————————————————————————————————", 9);
    y -= 4;
    if (stamp.html) {
      const plain = stamp.html.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim();
      const chunks = plain.match(/.{1,88}/g) || [];
      for (const chunk of chunks.slice(0, 60)) draw(chunk, 9);
    }
    y -= 16;
  };

  section("1. Signed Contract / Order", input.contract);
  section("2. Signed Credit Card Authorization", input.ccAuth);
  section("3. Carrier Confirmation (landing page click)", input.carrierClick);

  y -= 8;
  draw("Generated by Fast Break CRM. Upload this PDF directly to Stripe under Customer signature.", 8);

  return pdf.save();
}
